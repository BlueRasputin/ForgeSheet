#!/usr/bin/env node
// Bundles every SRD 5.1 spell from dnd5eapi.co into js/srd-spells.js so the app has them offline.
// SRD 5.1 is CC-BY-4.0 (attribution in README). Run: node tools/build_srd_spells.js
const fs = require("fs");
const path = require("path");
const API = "https://www.dnd5eapi.co/api/2014";
const KEEP = ["index", "name", "level", "school", "classes", "casting_time", "range", "components", "material",
  "duration", "concentration", "ritual", "desc", "higher_level", "damage", "dc", "attack_type", "heal_at_slot_level", "area_of_effect"];

(async () => {
  const list = (await (await fetch(`${API}/spells`)).json()).results;
  const spells = [];
  // The API allows 100 requests per second; 10 at a time with a pause stays well under it.
  for (let i = 0; i < list.length; i += 10) {
    const batch = await Promise.all(list.slice(i, i + 10).map(item => fetch(`${API}/spells/${item.index}`).then(res => res.json())));
    await new Promise(resolve => setTimeout(resolve, 250));
    batch.forEach(detail => {
      const kept = Object.fromEntries(KEEP.filter(key => detail[key] !== undefined).map(key => [key, detail[key]]));
      kept.school = { index: detail.school.index, name: detail.school.name };
      kept.classes = detail.classes.map(({ index, name }) => ({ index, name }));
      kept.source = "SRD";
      // The API writes "Up to 1 hour"; the app's spell data says "Concentration, up to 1 hour".
      if (kept.concentration && !/^concentration/i.test(kept.duration)) kept.duration = `Concentration, ${kept.duration.charAt(0).toLowerCase()}${kept.duration.slice(1)}`;
      spells.push(kept);
    });
  }
  spells.sort((a, b) => a.index.localeCompare(b.index));
  const out = "// Generated by tools/build_srd_spells.js from dnd5eapi.co. Contains SRD 5.1 material by Wizards of the Coast,\n" +
    "// licensed CC-BY-4.0 (https://creativecommons.org/licenses/by/4.0/). Do not edit by hand.\n" +
    "const SRD_SPELLS = " + JSON.stringify(spells) + ";\n";
  fs.writeFileSync(path.join(__dirname, "..", "js", "srd-spells.js"), out);
  console.log(`Wrote ${spells.length} SRD spells`);
})();
