#!/usr/bin/env node
// Bundles the SRD 5.1 beasts (Wild Shape forms, familiars) from dnd5eapi.co into js/srd-beasts.js.
// SRD 5.1 is CC-BY-4.0 (attribution in README). Run: node tools/build_srd_beasts.js
const fs = require("fs");
const path = require("path");
const API = "https://www.dnd5eapi.co/api/2014";

(async () => {
  const list = (await (await fetch(`${API}/monsters`)).json()).results;
  const beasts = [];
  // The API allows 100 requests per second; 10 at a time with a pause stays well under it.
  for (let i = 0; i < list.length; i += 10) {
    const batch = await Promise.all(list.slice(i, i + 10).map(item => fetch(`${API}/monsters/${item.index}`).then(res => res.json())));
    await new Promise(resolve => setTimeout(resolve, 250));
    batch.filter(detail => detail.type === "beast").forEach(detail => beasts.push({
      index: detail.index,
      name: detail.name,
      size: detail.size,
      cr: detail.challenge_rating,
      ac: detail.armor_class?.[0]?.value ?? 10,
      hp: detail.hit_points,
      speed: detail.speed,
      str: detail.strength, dex: detail.dexterity, con: detail.constitution,
      int: detail.intelligence, wis: detail.wisdom, cha: detail.charisma,
      senses: detail.senses,
      actions: (detail.actions || []).map(action => ({
        name: action.name,
        attack: action.attack_bonus ?? null,
        damage: (action.damage || []).map(part => part.damage_dice && `${part.damage_dice} ${part.damage_type?.name?.toLowerCase() || ""}`.trim()).filter(Boolean).join(" + "),
        desc: action.desc
      })),
      traits: (detail.special_abilities || []).map(trait => ({ name: trait.name, desc: trait.desc }))
    }));
  }
  beasts.sort((a, b) => a.cr - b.cr || a.name.localeCompare(b.name));
  const out = "// Generated by tools/build_srd_beasts.js from dnd5eapi.co. Contains SRD 5.1 material by Wizards of the Coast,\n" +
    "// licensed CC-BY-4.0 (https://creativecommons.org/licenses/by/4.0/). Do not edit by hand.\n" +
    "const SRD_BEASTS = " + JSON.stringify(beasts) + ";\n";
  fs.writeFileSync(path.join(__dirname, "..", "js", "srd-beasts.js"), out);
  console.log(`Wrote ${beasts.length} SRD beasts`);
})();
