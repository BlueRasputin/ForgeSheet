#!/usr/bin/env node
// Bundles the 2024 rules from SRD 5.2 (dnd5eapi.co /api/2024) into js/srd-2024.js: each core class's level table
// (features with their text, prepared spells, cantrips, slots, class resources), its SRD subclass, the SRD feats,
// and the SRD spells.
// SRD 5.2 is CC-BY-4.0 (attribution in README). Run: node tools/build_srd_2024.js
const fs = require("fs");
const path = require("path");
const API = "https://www.dnd5eapi.co/api/2024";

const get = async url => {
  const response = await fetch(`${API}${url}`);
  if (!response.ok) throw new Error(`${url}: ${response.status}`);
  return response.json();
};
// The API allows 100 requests per second; 10 at a time with a pause stays well under it.
const batched = async (items, load) => {
  const out = [];
  for (let i = 0; i < items.length; i += 10) {
    out.push(...await Promise.all(items.slice(i, i + 10).map(load)));
    await new Promise(resolve => setTimeout(resolve, 250));
  }
  return out;
};
// The SRD text comes from a PDF: rejoin words split across lines ("ex- pended") and tidy spacing.
const clean = text => String(text || "").replace(/([a-z])- ([a-z])/g, "$1$2").replace(/[ \t]*\n[ \t]*/g, "\n").replace(/\n{2,}/g, "\n").trim();

(async () => {
  const classIndexes = (await get("/classes")).results.map(item => item.index);
  const features = Object.fromEntries((await batched((await get("/features")).results, item => get(`/features/${item.index}`)))
    .map(detail => [detail.index, clean(detail.description || [detail.desc].flat().join("\n"))]));
  const classes = {};
  for (const index of classIndexes) {
    const [cls, levels] = await Promise.all([get(`/classes/${index}`), get(`/classes/${index}/levels`)]);
    const subclass = cls.subclasses?.[0] ? await get(`/subclasses/${cls.subclasses[0].index}`) : null;
    classes[index] = {
      hitDie: cls.hit_die,
      levels: levels.sort((a, b) => a.level - b.level).map(level => {
        const casting = level.spellcasting || null;
        return {
          level: level.level,
          features: (level.features || []).map(feature => ({ name: feature.name, text: features[feature.index] || "" })),
          prepared: casting ? casting.prepared_spells || 0 : 0,
          cantrips: casting ? casting.cantrips_known || 0 : 0,
          slots: casting ? Array.from({ length: 9 }, (_, slot) => casting[`spell_slots_level_${slot + 1}`] || 0) : [],
          specific: level.class_specific || {}
        };
      }),
      subclass: subclass ? {
        index: subclass.index,
        name: subclass.name,
        features: (subclass.features || []).map(feature => ({ level: feature.level, name: feature.name, text: clean(feature.description) }))
      } : null
    };
  }
  const feats = (await batched((await get("/feats")).results, item => get(`/feats/${item.index}`))).map(feat => ({
    name: feat.name,
    type: feat.type,
    prereq: feat.prerequisites || {},
    repeatable: Boolean(feat.repeatable),
    text: clean(feat.description)
  }));
  const spells = (await batched((await get("/spells")).results, item => get(`/spells/${item.index}`))).map(spell => ({
    index: spell.index,
    name: spell.name,
    level: spell.level,
    school: spell.school?.name || "",
    classes: (spell.classes || []).map(item => item.index),
    casting_time: spell.casting_time,
    range: spell.range,
    components: spell.components || [],
    material: spell.material || "",
    duration: spell.duration,
    concentration: Boolean(spell.concentration),
    ritual: Boolean(spell.ritual),
    text: clean(spell.description),
    higher_level: clean(spell.higher_level)
  })).sort((a, b) => a.index.localeCompare(b.index));
  const out = "// Generated by tools/build_srd_2024.js from dnd5eapi.co (/api/2024). Contains SRD 5.2 material by Wizards of the Coast,\n" +
    "// licensed CC-BY-4.0 (https://creativecommons.org/licenses/by/4.0/). Do not edit by hand.\n" +
    "const SRD_2024_CLASSES = " + JSON.stringify(classes) + ";\n" +
    "const SRD_2024_FEATS = " + JSON.stringify(feats) + ";\n" +
    "const SRD_2024_SPELLS = " + JSON.stringify(spells) + ";\n";
  fs.writeFileSync(path.join(__dirname, "..", "js", "srd-2024.js"), out);
  console.log(`Wrote ${Object.keys(classes).length} classes, ${feats.length} feats and ${spells.length} spells (${Math.round(out.length / 1024)} KB)`);
})();
